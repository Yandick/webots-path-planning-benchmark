"""Generate Webots geometry from the exact same scene registry used in evaluation."""
import argparse
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from navigation.scenarios import SCENES, make_scene, validate_scene


def world_text(scene):
    meta = json.dumps(json.dumps({"scene": scene.name, "seed": scene.seed}))
    robot = (ROOT / "assets" / "robot.wbo.in").read_text(encoding="utf-8")
    for key, value in {"START_X": scene.start[0], "START_Y": scene.start[1],
                       "START_YAW": math.atan2(scene.goal[1]-scene.start[1], scene.goal[0]-scene.start[0]),
                       "SCENE_METADATA": meta}.items():
        robot = robot.replace("{{"+key+"}}", str(value))
    text = ['#VRML_SIM R2025a utf8', '# Generated by scripts/generate_worlds.py; edit navigation/scenarios.py.',
            'WorldInfo { basicTimeStep 32 coordinateSystem "ENU" randomSeed 1 }',
            'Viewpoint { orientation 0 1 0 1.57079632679 position 0 0 13 }',
            'Background { skyColor [0.86 0.91 0.97] }',
            'DirectionalLight { direction 0.3 0.3 -1 intensity 1 castShadows TRUE }',
            'Solid { translation 0 0 -0.05 children [ Shape { appearance PBRAppearance { baseColor 0.9 0.9 0.9 roughness 1 } geometry Box { size 10.2 10.2 .1 } } ] boundingObject Box { size 10.2 10.2 .1 } }']
    for i, obs in enumerate(scene.static):
        x, y = obs.params["center"]
        geom = (f'Box {{ size {obs.params["size"][0]} {obs.params["size"][1]} .8 }}' if obs.kind=="box"
                else f'Cylinder {{ radius {obs.params["radius"]} height .8 }}')
        text.append(f'DEF STATIC_{i} Solid {{ translation {x} {y} .4 name "static_{i}" children [ Shape {{ appearance PBRAppearance {{ baseColor .3 .4 .55 roughness 1 }} geometry {geom} }} ] boundingObject {geom} }}')
    for i, obs in enumerate(scene.moving):
        x, y = obs.position(0)
        # Kinematic actors are explicit. No resetPhysics and no dynamic body teleportation.
        text.append(f'DEF MOVING_{i} Solid {{ translation {x} {y} .35 name "cart_{i}" children [ Shape {{ appearance PBRAppearance {{ baseColor .95 .25 .12 roughness 1 }} geometry Cylinder {{ radius {obs.radius} height .7 }} }} ] boundingObject Cylinder {{ radius {obs.radius} height .7 }} }}')
    for name, position, color in (("start", scene.start, ".1 .8 .2"), ("goal", scene.goal, ".9 .15 .15")):
        x, y = position
        text.append(f'Solid {{ translation {x} {y} .005 name "{name}" children [ Shape {{ appearance PBRAppearance {{ baseColor {color} }} geometry Cylinder {{ radius .25 height .01 }} }} ] }}')
    text += [robot, f'DEF SUPERVISOR Robot {{ name "supervisor" controller "coursework_supervisor" supervisor TRUE customData {meta} }}']
    return "\n\n".join(text)+"\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()
    for name in SCENES:
        scene = make_scene(name, args.seed)
        validate_scene(scene)
        text = world_text(scene)
        (ROOT / "worlds" / f"{name}.wbt").write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
